    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed


    String identificacion = txtIdentificacion.getText().trim();

    // Verificar que se haya escrito una identificación
    if (identificacion.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Digite la identificación del estudiante que desea eliminar.",
                "Dato requerido",
                JOptionPane.WARNING_MESSAGE
        );

        txtIdentificacion.requestFocus();
        return;
    }

    // Verificar que el estudiante exista
    Estudiante estudiante = lista.buscarIdentificacion(identificacion);

    if (estudiante == null) {

        JOptionPane.showMessageDialog(
                this,
                "No existe un estudiante con la identificación: "
                + identificacion,
                "Estudiante no encontrado",
                JOptionPane.INFORMATION_MESSAGE
        );

        return;
    }

    // Confirmar eliminación
    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de eliminar al estudiante?\n\n"
            + "Nombre: " + estudiante.getNombre() + "\n"
            + "Identificación: " + estudiante.getIdentificacion(),
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
    );

    if (respuesta == JOptionPane.YES_OPTION) {

        // Eliminar de la lista enlazada
        boolean eliminado = lista.eliminar(identificacion);

        if (eliminado) {

            JOptionPane.showMessageDialog(
                    this,
                    "Estudiante eliminado correctamente.",
                    "Eliminación exitosa",
                    JOptionPane.INFORMATION_MESSAGE
            );

            // Actualizar la tabla
            cargarTabla();

            // Limpiar formulario
            limpiarCampos();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No fue posible eliminar el estudiante.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
      // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed

